# 1) შედარება კომენტარებით:
# მეტობა        --> >
# ნაკლობა       --> <
# ტოლობა        --> ==
# არათოლობა     --> !=
# მეტია ან ტოლი  --> >=
# ნაკლები ან ტოლი --> <=

# მაგალითები:
print(5 > 3)    # True, 5 მეტია 3-ზე
print(2 < 8)    # True, 2 ნაკლებია 8-ზე
print(4 == 4)   # True, 4 ტოლია 4-ის
print(6 != 7)   # True, 6 არ არის ტოლი 7-ის
print(9 >= 9)   # True, 9 მეტია ან ტოლია 9-ის
print(1 <= 5)   # True, 1 ნაკლებია ან ტოლია 5-ის

